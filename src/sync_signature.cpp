bool verify_sync_signature(const std::string& version,const std::string& sha256_hex,const std::string& signature_base64) {
    if(version.empty()||sha256_hex.size()!=64) return false;
    std::vector<unsigned char> signature;
    if(!decode_base64(signature_base64,signature)||signature.size()!=256) return false;

    const std::string payload="JOSTS-SYNC-1\n"+version+"\n"+sha256_hex+"\n";
    unsigned char digest[32]{};
    if(!hash_sha256(payload,digest)) return false;

    std::vector<unsigned char> blob(sizeof(BCRYPT_RSAKEY_BLOB)+sizeof(PublicExponent)+sizeof(PublicModulus));
    auto* header=reinterpret_cast<BCRYPT_RSAKEY_BLOB*>(blob.data());
    header->Magic=BCRYPT_RSAPUBLIC_MAGIC;
    header->BitLength=2048;
    header->cbPublicExp=sizeof(PublicExponent);
    header->cbModulus=sizeof(PublicModulus);
    header->cbPrime1=0; header->cbPrime2=0;
    unsigned char* cursor=blob.data()+sizeof(BCRYPT_RSAKEY_BLOB);
    std::memcpy(cursor,PublicExponent,sizeof(PublicExponent)); cursor+=sizeof(PublicExponent);
    std::memcpy(cursor,PublicModulus,sizeof(PublicModulus));

    BCRYPT_ALG_HANDLE alg=nullptr; BCRYPT_KEY_HANDLE key=nullptr;
    NTSTATUS status=BCryptOpenAlgorithmProvider(&alg,BCRYPT_RSA_ALGORITHM,nullptr,0);
    if(status>=0) status=BCryptImportKeyPair(alg,nullptr,BCRYPT_RSAPUBLIC_BLOB,&key,blob.data(),static_cast<ULONG>(blob.size()),0);
    if(status>=0) {
        BCRYPT_PKCS1_PADDING_INFO padding{BCRYPT_SHA256_ALGORITHM};
        status=BCryptVerifySignature(key,&padding,digest,sizeof(digest),signature.data(),static_cast<ULONG>(signature.size()),BCRYPT_PAD_PKCS1);
    }
    if(key) BCryptDestroyKey(key);
    if(alg) BCryptCloseAlgorithmProvider(alg,0);
    return status>=0;
}
